function mergeAtlasRows(base,local,remote){
 const baseline=new Map(base.map(row=>[row.id,row]));
 const current=new Map(local.map(row=>[row.id,row]));
 const server=new Map(remote.map(row=>[row.id,row]));
 const merged=new Map(server);
 for(const id of new Set([...baseline.keys(),...current.keys()])){
   const previous=baseline.get(id), draft=current.get(id), latest=server.get(id);
   if(sameValue(previous,draft)||sameValue(draft,latest))continue;
   if(sameValue(previous,latest)){if(draft)merged.set(id,draft);else merged.delete(id);continue;}
   if(!draft||!latest||!previous)throw Error('conflict');
   const result={...latest};
   for(const key of new Set([...Object.keys(previous),...Object.keys(draft)])){
     if(sameValue(previous[key],draft[key]))continue;
     if(!sameValue(previous[key],latest[key])&&!sameValue(draft[key],latest[key])){
       if(['cities','natural','related','excluded','peers','links'].includes(key)&&[previous[key],draft[key],latest[key]].every(Array.isArray)){
         const kept=new Set(latest[key]);
         for(const id of previous[key])if(!draft[key].includes(id))kept.delete(id);
         for(const id of draft[key])if(!previous[key].includes(id))kept.add(id);
         result[key]=[...kept];
         continue;
       }
       throw Error('conflict');
     }
     if(draft[key]===undefined)delete result[key];else result[key]=draft[key];
   }
   merged.set(id,result);
 }
 return [...merged.values()];
}
