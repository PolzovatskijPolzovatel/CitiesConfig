$('geoButton').onclick=()=>$('geoFile').click();
$('geoFile').onchange=async e=>{
 const file=e.target.files[0];e.target.value='';
 if(!file)return;
 try{
   if(file.size>18000000)throw Error('Размер GeoJSON превышает 18 МБ');
   const result=parseGeoJSON(JSON.parse(await file.text()));
   if(!result.items.length)throw Error('Нет объектов, которые можно добавить');
   if(dirty)commit();
   items.push(...result.items);
   layer='all';collectionFilter='all';typeFilter='any';drawing=null;moving=false;activeTool=null;
   selected=result.items[0].id;
   render();center(chosen());togglePop(dataBtn,dataPop,false);
   const info='Добавлено: '+result.items.length+(result.skipped?' · пропущено: '+result.skipped:'');
   saveMessage(persist(),info);
 }catch(error){toast(error instanceof SyntaxError?'Не удалось прочитать GeoJSON':error.message);}
};
$('importButton').onclick=()=>$('importFile').click();
let pendingImport=null;
$('importFile').onchange=async e=>{
 const f=e.target.files[0];e.target.value='';if(!f)return;
 try{
   if(f.size>18000000)throw new Error();
   const data=JSON.parse(await f.text());
   if(data.format!=='atlas-prostranstva'||data.version!==1)throw new Error();
   pendingImport={items:normalize(data.items),collections:normalizeCollections(data.collections)};$('importText').textContent='В копии '+pendingImport.items.length+' '+variantCount(pendingImport.items.length)+'. Если открыть её, текущие знаки и статьи будут заменены.';
   togglePop(dataBtn,dataPop,false);$('importDialog').showModal();
 }catch{toast('Не удалось открыть файл: выберите JSON-копию этого атласа.');}
};
