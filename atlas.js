function packedHitGeometry(feature){
 let packed=naturalHitCache.get(feature);
 if(!packed){
   const parts=geometryParts(feature.geometry).filter(part=>part.paths).map(part=>({
     area:part.area,
     paths:part.paths.map(path=>path.map(([x,lat])=>[x,naturalProject(lat)]))
   }));
   const bounds=feature.bounds||coordinatesBounds(geometryParts(feature.geometry).flatMap(part=>part.paths?.flat()||[part.point]));
   packed={parts,west:bounds[0],east:bounds[2],top:naturalProject(bounds[3]),bottom:naturalProject(bounds[1])};
   naturalHitCache.set(feature,packed);
 }
 return packed;
}
function squaredDistanceToSegment(x,y,ax,ay,bx,by){
 const dx=bx-ax,dy=by-ay;
 const length=dx*dx+dy*dy;
 const t=length?clamp(((x-ax)*dx+(y-ay)*dy)/length,0,1):0;
 return (x-ax-t*dx)**2+(y-ay-t*dy)**2;
}
function measureNaturalGeometry(parts,x,y,tolerance){
 let distance=tolerance*tolerance;
 for(const {paths,area} of parts){
   let inside=false;
   for(const ring of paths){
     for(let index=1;index<ring.length;index++){
       const [ax,ay]=ring[index-1],[bx,by]=ring[index];
       if(area&&(ay>y)!==(by>y)&&x<(bx-ax)*(y-ay)/(by-ay)+ax)inside=!inside;
       if(x<Math.min(ax,bx)-tolerance||x>Math.max(ax,bx)+tolerance||
          y<Math.min(ay,by)-tolerance||y>Math.max(ay,by)+tolerance)continue;
       distance=Math.min(distance,squaredDistanceToSegment(x,y,ax,ay,bx,by));
     }
   }
   if(inside)return {inside:true,distance:0};
 }
 return distance<tolerance*tolerance?{inside:false,distance}:null;
}
function findNaturalHit(px,py,tolerancePixels=8,preferRiver=false){
 const scale=vis.base*vis.zoom;
 const lon=vis.lon+(px-vis.width/2)/scale;
 const y=vis.y+(py-vis.height/2)/scale;
 const tolerance=tolerancePixels/scale;
 let best=null;
 for(const {bin,offset} of visibleNaturalBins.values()){
   const x=lon-offset;
   if(x<bin.west-tolerance||x>bin.east+tolerance||y<bin.top-tolerance||y>bin.bottom+tolerance)continue;
   for(const feature of bin.features){
     if(!feature.title||preferRiver&&feature.kind!=='river')continue;
     const bounds=feature.bounds;
     if(bounds&&(x<bounds[0]-tolerance||x>bounds[2]+tolerance))continue;
     const candidate=packedHitGeometry(feature);
     if(x<candidate.west-tolerance||x>candidate.east+tolerance||y<candidate.top-tolerance||y>candidate.bottom+tolerance)continue;
     const hit=measureNaturalGeometry(candidate.parts,x,y,tolerance);
     if(!hit)continue;
     const specificity=(candidate.east-candidate.west)*(candidate.bottom-candidate.top);
     const order=hit.inside?0:1;
     if(!best||order<best.order||
        order===best.order&&(hit.distance<best.distance||
          hit.distance===best.distance&&specificity<best.specificity)){
       best={feature,offset,order,distance:hit.distance,specificity};
     }
   }
 }
 return best;
}
function activeMapHit(x,y,tolerance,preferRiver){
 const existing=preferRiver?null:editorRelatedHit(x,y,tolerance);
 const natural=findNaturalHit(x,y,tolerance,preferRiver);
 if(existing&&(!natural||existing.order<=natural.order&&existing.distance<=Math.max(natural.distance,0.000001)))return existing;
 return natural;
}
