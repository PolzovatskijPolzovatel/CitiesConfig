function readGeometry(geometry, budget={points:100000}, depth=0){
 if(!geometry||!GEOMETRY_TYPES.has(geometry.type)||depth>8)throw Error('Некорректная геометрия');
 function position(value){
   if(!Array.isArray(value)||value.length<2||!value.slice(0,2).every(Number.isFinite)||Math.abs(value[0])>180||Math.abs(value[1])>90||--budget.points<0)throw Error('Некорректные координаты');
   return [value[0],clamp(value[1],-MAX_LAT,MAX_LAT)];
 }
 function group(value,read,min=1){
   if(!Array.isArray(value)||value.length<min)throw Error('Неполная геометрия');
   return value.map(read);
 }
 const line=value=>group(value,position,2);
 const ring=value=>{
   const points=group(value,position,3);
   const first=points[0],last=points.at(-1);
   if(first[0]!==last[0]||first[1]!==last[1])points.push(first);
   if(points.length<4)throw Error('Неполный контур');
   return points;
 };
 const polygon=value=>group(value,ring);
 const {type,coordinates}=geometry;
 if(type==='GeometryCollection')return {type,geometries:group(geometry.geometries,g=>readGeometry(g,budget,depth+1))};
 const readers={
   Point:position,MultiPoint:value=>group(value,position),LineString:line,MultiLineString:value=>group(value,line),
   Polygon:polygon,MultiPolygon:value=>group(value,polygon)
 };
 return {type,coordinates:readers[type](coordinates)};
}

function geometryParts(geometry){
 const {type,coordinates}=geometry;
 switch(type){
   case 'Point': return [{point:coordinates}];
   case 'MultiPoint': return coordinates.map(point=>({point}));
   case 'LineString': return [{paths:[coordinates],area:false}];
   case 'MultiLineString': return coordinates.map(line=>({paths:[line],area:false}));
   case 'Polygon': return [{paths:coordinates,area:true}];
   case 'MultiPolygon': return coordinates.map(paths=>({paths,area:true}));
   case 'GeometryCollection': return geometry.geometries.flatMap(geometryParts);
 }
}
